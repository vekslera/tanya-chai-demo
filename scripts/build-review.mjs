// Generates the review document (SPEC §8.4): every reviewable item in reading order, with its id,
// so Alex can review the drafts in one pass.
import fs from 'node:fs';
import { pathOf } from './lib/config.ts';
import { loadAll } from './lib/content.mjs';

const all = loadAll();
const byId = new Map(all.units.map((u) => [u.id, u]));
const content = new Map(all.unitContent.map((c) => [c.id, c]));
const glossary = new Map(all.glossary.map((g) => [g.id, g]));
const p = all.portion;
const portionUnits = p ? all.schedule[p.yearType][p.dateKey].flatMap(unitsIn) : [];

function unitsIn({ from, to }) {
  const lo = byId.get(from).seq;
  const hi = byId.get(to).seq;
  return all.units.filter((u) => u.seq >= lo && u.seq <= hi);
}

const status = (r) => (r.reviewed ? '✅ approved' : '⬜ to review');
const item = (id, r) => {
  const lines = [`- **${id}** (${status(r)})`, `  ${r.value}`];
  if (r.note) lines.push(`  _Note: ${r.note}_`);
  return lines.join('\n');
};

const out = [];
out.push('# Content review: ' + (p?.label.he ?? ''));
out.push('');
out.push(
  'Generated by `npm run review` from the JSON in `content/`. Do not edit the layout by hand: mark corrections next to an item (or edit the JSON directly), and Claude Code applies them and sets `reviewed: true` only for the items you approve.',
);
out.push('');
const unreviewed = [];
const count = (r) => {
  if (!r.reviewed) unreviewed.push(r);
  return r;
};

out.push('## 1. Text and short ביאור');
out.push('');
let paragraph = 0;
for (const u of portionUnits) {
  if (u.paragraph !== paragraph) {
    paragraph = u.paragraph;
    out.push(`### Paragraph ${paragraph}`);
    out.push('');
  }
  const c = content.get(u.id);
  out.push(`#### ${u.id}`);
  out.push('');
  out.push(`> ${u.text.trim()}`);
  out.push('');
  if (c?.biur?.short) out.push(item(`${u.id}/biur`, count(c.biur.short)));
  for (const m of c?.glossary ?? []) {
    const g = glossary.get(m.entryId);
    out.push(item(`glossary/${g.id}: ${g.term}`, count(g.body)));
    if (g.source) out.push(`  Source line: ${g.source}`);
  }
  out.push('');
}

out.push('## 2. Questions');
out.push('');
const sections = [
  ['Level 1: text only (3 literal)', (q) => q.track === 'solo' && q.level === 1],
  [
    'Level 2: text with ביאור (2 understanding, 1 concept)',
    (q) => q.track === 'solo' && q.level === 2,
  ],
  ["Avos uBanim: the son's questions", (q) => q.track === 'together'],
];
for (const [title, test] of sections) {
  out.push(`### ${title}`);
  out.push('');
  for (const q of p.questions.filter(test)) {
    out.push(`#### ${q.id} (${q.kind}, ${q.category}), relies on ${q.unitRef}`);
    out.push('');
    out.push(item('prompt', count(q.prompt)));
    if (q.kind === 'choice') {
      for (const o of q.options) out.push(`  - ${o.id === q.answer ? '**✔**' : '✘'} ${o.text}`);
    } else if (q.kind === 'trueFalse') {
      out.push(`  Answer: ${q.answer === 'true' ? 'נכון' : 'לא נכון'}`);
    } else {
      out.push(`  Answer: ${q.answer}: ${byId.get(q.answer).text.trim()}`);
    }
    out.push(item('hint', count(q.hint)));
    out.push(item('explanation', count(q.explanation)));
    out.push('');
  }
}

out.push('## 3. Avos uBanim cards');
out.push('');
for (const c of p.together) {
  out.push(`### ${c.id} (${c.from}–${c.to})`);
  out.push('');
  out.push(
    `> ${unitsIn(c)
      .map((u) => u.text.trim())
      .join(' ')}`,
  );
  out.push('');
  out.push(item('לאבא (forParent)', count(c.forParent)));
  out.push(item('לומר לילד (toChild)', count(c.toChild)));
  if (c.talk) out.push(item('שאלה לשיחה (talk)', count(c.talk)));
  out.push('');
}

out.splice(4, 0, `**Status:** ${unreviewed.length} item(s) to review.`, '');
fs.writeFileSync(pathOf('review', all, { absolute: true }), out.join('\n'));
console.log(`review: wrote ${pathOf('review', all)} (${unreviewed.length} to review)`);
